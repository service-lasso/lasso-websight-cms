import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspaceRoot = path.resolve(process.env.WEBSIGHT_LIVE_WORKSPACE ?? path.join(repoRoot, "output", "live-stack", process.platform));
const servicesRoot = path.join(workspaceRoot, "services");
const coreRepo = path.resolve(process.env.SERVICE_LASSO_REPO ?? path.join(repoRoot, "..", "service-lasso"));
const coreDist = path.join(coreRepo, "dist");
const stackServiceIds = ["@java", "@node", "mongo", "nginx", "totaljs-messageservice", "totaljs-flow", "websight-cms"];

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function run(command, args, options = {}) {
  const spawnCommand = process.platform === "win32" && command === "npm" ? "cmd.exe" : command;
  const spawnArgs = process.platform === "win32" && command === "npm" ? ["/d", "/s", "/c", ["npm", ...args].join(" ")] : args;
  const result = spawnSync(spawnCommand, spawnArgs, {
    cwd: repoRoot,
    stdio: "inherit",
    shell: false,
    ...options,
  });

  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(" ")} failed with exit code ${result.status}: ${result.error?.message ?? ""}`);
  }
}

async function copyManifest(serviceId, sourceFile) {
  const targetDir = path.join(servicesRoot, serviceId);
  await mkdir(targetDir, { recursive: true });
  await cp(sourceFile, path.join(targetDir, "service.json"));
}

async function prepareConsumerWorkspace() {
  await rm(workspaceRoot, { recursive: true, force: true });
  await mkdir(servicesRoot, { recursive: true });

  await copyManifest("@java", path.join(coreRepo, "services", "@java", "service.json"));
  await copyManifest("@node", path.join(coreRepo, "services", "@node", "service.json"));
  await copyManifest("mongo", path.join(repoRoot, "..", "lasso-mongo", "service.json"));
  await copyManifest("nginx", path.join(repoRoot, "..", "lasso-nginx", "service.json"));
  await copyManifest("totaljs-messageservice", path.join(repoRoot, "..", "lasso-totaljs-messageservice", "service.json"));
  await copyManifest("totaljs-flow", path.join(repoRoot, "..", "lasso-totaljs-flow", "service.json"));
  await copyManifest("websight-cms", path.join(repoRoot, "service.json"));

  await writeFile(
    path.join(workspaceRoot, "README.md"),
    [
      "# Websight CMS Live Verification Workspace",
      "",
      "Generated by `npm run verify:live`.",
      "",
      "This workspace intentionally lives under `output/` so runtime state, downloaded archives, logs, and CMS repository data never land in the service repo source tree.",
      "",
    ].join("\n"),
  );
}

async function importCoreModule(relativePath) {
  const modulePath = path.join(coreDist, relativePath);
  assert(existsSync(modulePath), `Missing Service Lasso core module: ${modulePath}. Run npm run build in ${coreRepo} or set SERVICE_LASSO_REPO.`);
  return import(pathToFileURL(modulePath).href);
}

async function requestStatus(url, timeoutMs = 10_000) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const response = await fetch(url, { signal: controller.signal, redirect: "manual" });
    await response.arrayBuffer();
    return response.status;
  } finally {
    clearTimeout(timeout);
  }
}

async function assertUrlResolves(label, url, allowedStatuses) {
  const status = await requestStatus(url);
  assert(allowedStatuses.includes(status), `${label} ${url} returned ${status}; expected one of ${allowedStatuses.join(", ")}`);
  console.log(`[lasso-websight-cms] ${label} resolved with HTTP ${status}: ${url}`);
}

async function persistLifecycleResult(writeServiceState, service, result) {
  await writeServiceState(service, result.state);
  assert(result.ok, `${service.manifest.id} lifecycle action failed: ${result.message}`);
  return result;
}

function getRequiredService(registry, serviceId) {
  const service = registry.getById(serviceId);
  assert(service, `Service ${serviceId} was not discovered in live workspace.`);
  return service;
}

async function stopRunningServices(registry, stopService, writeServiceState) {
  for (const serviceId of [...stackServiceIds].reverse()) {
    const service = registry.getById(serviceId);
    if (!service) {
      continue;
    }
    try {
      const result = await stopService(service);
      await writeServiceState(service, result.state);
      console.log(`[lasso-websight-cms] stopped ${serviceId}`);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      if (!message.includes("is not running")) {
        console.warn(`[lasso-websight-cms] stop warning for ${serviceId}: ${message}`);
      }
    }
  }
}

assert(existsSync(coreRepo), `Service Lasso core repo not found: ${coreRepo}`);
run("npm", ["run", "build"], { cwd: coreRepo });
await prepareConsumerWorkspace();

const { bootstrapBaselineServices } = await importCoreModule(path.join("runtime", "cli", "bootstrap.js"));
const { restartService, stopService } = await importCoreModule(path.join("runtime", "lifecycle", "actions.js"));
const { getLifecycleState } = await importCoreModule(path.join("runtime", "lifecycle", "store.js"));
const { writeServiceState } = await importCoreModule(path.join("runtime", "state", "writeState.js"));

let registry;
try {
  const bootstrap = await bootstrapBaselineServices({
    servicesRoot,
    workspaceRoot,
    serviceIds: stackServiceIds,
  });
  registry = bootstrap.registry;

  const failed = bootstrap.services.filter((service) => service.status !== "completed");
  assert(failed.length === 0, `Live stack bootstrap did not complete: ${JSON.stringify(failed, null, 2)}`);

  for (const serviceId of stackServiceIds) {
    const service = bootstrap.services.find((candidate) => candidate.serviceId === serviceId);
    assert(service, `Missing bootstrap summary for ${serviceId}`);
    console.log(`[lasso-websight-cms] ${serviceId}: ${service.actions.map((action) => `${action.action}:${action.status}`).join(", ")}`);
  }

  const cmsState = getLifecycleState("websight-cms");
  assert(cmsState.running, "websight-cms did not reach running state.");
  assert(cmsState.runtime.provider === "java", `Expected websight-cms to run through the Java provider, got ${cmsState.runtime.provider}`);
  assert(cmsState.runtime.providerServiceId === "@java", `Expected websight-cms provider @java, got ${cmsState.runtime.providerServiceId}`);

  const cmsPort = cmsState.runtime.ports.service;
  assert(cmsPort, `Missing negotiated CMS service port: ${JSON.stringify(cmsState.runtime.ports)}`);
  const cmsUrl = `http://127.0.0.1:${cmsPort}`;
  const cmsAuthUrl = `${cmsUrl}/apps/websight-authentication/login.html`;

  await assertUrlResolves("CMS health", `${cmsUrl}/system/health`, [200]);
  await assertUrlResolves("CMS root", `${cmsUrl}/`, [200, 302, 401, 403]);
  await assertUrlResolves("CMS login", cmsAuthUrl, [200, 302, 401, 403]);

  const cmsService = getRequiredService(registry, "websight-cms");
  await persistLifecycleResult(writeServiceState, cmsService, await restartService(cmsService, registry));
  await assertUrlResolves("CMS health after restart", `${cmsUrl}/system/health`, [200]);

  await persistLifecycleResult(writeServiceState, cmsService, await stopService(cmsService));
  assert(!getLifecycleState("websight-cms").running, "websight-cms remained running after stop.");

  console.log(`[lasso-websight-cms] live stack verified in ${workspaceRoot}`);
} finally {
  if (registry) {
    await stopRunningServices(registry, stopService, writeServiceState);
  }
}
